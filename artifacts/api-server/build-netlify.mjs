import path from "node:path";
import { fileURLToPath } from "node:url";
import { build as esbuild } from "esbuild";
import { mkdir, readdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";

const artifactDir = path.dirname(fileURLToPath(import.meta.url));

// Netlify reads the function directory relative to the site base, which netlify.toml
// points at the mobile app. The API is bundled into it rather than installed there:
// the output has no bare imports left, so the function zip carries no workspace copy
// of express, drizzle or pg, and Netlify never has to resolve `@workspace/*`.
const outFile = path.resolve(
  artifactDir,
  "../turiwa-mobile/netlify/functions/api.mjs",
);

async function buildNetlifyFunction() {
  const functionsDir = path.dirname(outFile);
  await rm(functionsDir, { recursive: true, force: true });
  await mkdir(functionsDir, { recursive: true });

  await esbuild({
    entryPoints: [path.resolve(artifactDir, "src/netlify.ts")],
    platform: "node",
    bundle: true,
    format: "esm",
    target: "node20",
    // pg-cloudflare exposes its real TCP socket only through the `workerd` export
    // condition. Without it, esbuild picks that package's intentional empty fallback.
    conditions: ["workerd"],
    outfile: outFile,
    outExtension: { ".js": ".mjs" },
    logLevel: "info",
    // The embedded file database is replaced by a stub that refuses to start, so no
    // trace of it stays in the bundle: a misconfigured deploy reports the missing
    // database instead of failing to load a native Postgres build, and the function
    // zip stays free of the 10 MB of WebAssembly that has no use on this host.
    alias: {
      "@electric-sql/pglite": path.resolve(artifactDir, "src/netlifyPgliteStub.ts"),
    },
    external: ["pg-native"],
    sourcemap: "linked",
    banner: {
      js: `import { createRequire as __bannerCrReq } from 'node:module';
import __bannerPath from 'node:path';
import __bannerUrl from 'node:url';

globalThis.require = __bannerCrReq(import.meta.url);
globalThis.__filename = __bannerUrl.fileURLToPath(import.meta.url);
globalThis.__dirname = __bannerPath.dirname(globalThis.__filename);
    `,
    },
  });

  console.log(`Netlify function written to ${outFile}`);
}

// The same two rules netlify.toml declares, written into the published directory so a
// folder uploaded straight to Netlify routes identically to a Git-connected build.
// Without them the browser asks `/api/state` of the static host, gets `index.html` back,
// and the app reports a malformed response instead of ever reaching the function.
const ROUTES = `# Generated by artifacts/api-server/build-netlify.mjs - edit netlify.toml, not this file.
/api/*  /.netlify/functions/api/:splat  200
/*      /index.html                     200
`;

const HEADERS = `# Generated by artifacts/api-server/build-netlify.mjs - edit netlify.toml, not this file.
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(), camera=(), microphone=()
  X-Frame-Options: DENY
`;

async function writeRoutingFiles() {
  await mkdir(DIST, { recursive: true });
  await writeFile(path.join(DIST, "_redirects"), ROUTES, "utf8");
  await writeFile(path.join(DIST, "_headers"), HEADERS, "utf8");
  console.log(`routing and headers written into ${DIST}`);
}

const DIST = path.resolve(artifactDir, "../turiwa-mobile/dist");

// Netlify never publishes a file under a path segment that begins with a dot, and Metro's
// pnpm layout puts every exported asset under `assets/__node_modules/.pnpm/...`. On the host
// all 52 fonts and icons were therefore absent, the `/* -> /index.html` rewrite answered with
// an HTML document where a font belongs, and Chrome read the leading `<!DO` as a broken
// sfntVersion — the whole app rendering in fallback type while looking fine on a dev server.
// Renaming that one segment, and every URL that points through it, is the entire fix.
const DOTTED = "__node_modules/.pnpm/";
const SHIPPABLE = "__node_modules/pnpm/";

async function rewriteTextFiles(dir, found) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      // Asset files are binary; their bytes can never contain a URL to themselves.
      if (entry.name !== "assets") await rewriteTextFiles(full, found);
    } else if (/\.(?:js|json|html|map)$/.test(entry.name)) {
      const text = await readFile(full, "utf8");
      if (!text.includes(DOTTED)) continue;
      await writeFile(full, text.replaceAll(DOTTED, SHIPPABLE), "utf8");
      found.push(full);
    }
  }
}

async function shipDottedAssets() {
  const from = path.join(DIST, "assets/__node_modules/.pnpm");
  const to = path.join(DIST, "assets/__node_modules/pnpm");
  // Check the source before touching the destination: once an export has been shipped there is
  // no `.pnpm` left to rename, so clearing `pnpm` first would delete the only copy of every
  // asset. That ordering is why this is a guarded check rather than a try/catch around both.
  const sourcePresent = await isDirectory(from);
  if (!sourcePresent) {
    if (await isDirectory(to)) {
      console.log(`assets already shipped from ${to}`);
      return;
    }
    throw new Error(`No export found at ${path.join(DIST, "assets")} - run \`expo export --platform web\` first.`);
  }

  await rm(to, { recursive: true, force: true });
  await rename(from, to);

  // A silent skip here used to publish a site whose every font answered with HTML, so verify
  // the move actually landed before anything downstream trusts this directory.
  if ((await isDirectory(from)) || !(await isDirectory(to))) {
    throw new Error(`rename(${from}, ${to}) reported success but the files did not move.`);
  }

  const found = [];
  await rewriteTextFiles(DIST, found);
  const shipped = await countFiles(to);
  if (found.length === 0) {
    throw new Error(`moved ${shipped} asset(s) but no file referenced ${DOTTED} - the URLs would still point at the dot directory.`);
  }
  console.log(`${shipped} assets moved out of the dot directory; URLs rewritten in ${found.length} file(s)`);
}

async function countFiles(dir) {
  let total = 0;
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    total += entry.isDirectory() ? await countFiles(path.join(dir, entry.name)) : 1;
  }
  return total;
}

async function isDirectory(target) {
  try {
    return (await stat(target)).isDirectory();
  } catch (err) {
    // Absent is a real answer; anything else (a typo in this file, a locked handle, EPERM)
    // must not read as "nothing to ship", because that is how a publish ends up asset-less.
    if (err.code === "ENOENT" || err.code === "ENOTDIR") return false;
    throw err;
  }
}

async function main() {
  // A Cloudflare Pages build serves the same `dist` but runs the API on the Node host, so it
  // must not overwrite netlify/functions/api.mjs with anything: it only needs the routing files
  // and the asset rename applied to the fresh export.
  if (process.env.EXPORT_ONLY !== "1") await buildNetlifyFunction();
  await writeRoutingFiles();
  await shipDottedAssets();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
